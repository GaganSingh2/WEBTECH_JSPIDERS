//3 ways to Declare Variable---------
//1) By Using var keyword
console.log("By Using var keyword------");

var a //Declaration
a = 10 //Initialization
console.log(a);

var b = 20 //Declaration + Initialization
console.log(b);

b = 30 //Re-Initialization
console.log(b);

var b //Re-Declaration

var b = 40 //Re-Declaration + Re-Initialization
console.log(b);


//2) By Using let keyword
console.log("By Using let keyword-------");

let x //Declaration
x = 20 //Initialization
console.log(x);

x = 30 //Re-Initialization
console.log(x);

let y = 40 //Declaration + Initialization
console.log(y);

// let y //Re-Declaration, Re-Declaration + Initialization is not allowed




