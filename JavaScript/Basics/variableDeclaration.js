//3 ways to Declare Variable---------
//1) By Using var keyword
var a //Declaration
a = 10 //Initialization
console.log(a);

var b = 20 //Declaration + Initialization
console.log(b);

b = 30 //Re-Initialization
console.log(b);

var b //Re-Declaration

var b = 40 //Re-Declaration + Re-Initialization
console.log(b);





